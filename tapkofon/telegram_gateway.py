"""The async Telethon API used here (its sync-compatible annotations differ)."""

from datetime import datetime
from typing import Any, Protocol


class QRLoginGateway(Protocol):
    @property
    def url(self) -> str: ...
    @property
    def expires(self) -> datetime: ...
    async def wait(self) -> Any: ...


class TelegramGateway(Protocol):
    parse_mode: str | None

    def is_connected(self) -> bool: ...
    async def connect(self) -> None: ...
    async def disconnect(self) -> None: ...
    async def start(self, **kwargs: Any) -> Any: ...
    async def is_user_authorized(self) -> bool: ...
    async def get_me(self) -> Any: ...
    async def get_entity(self, entity: Any) -> Any: ...
    async def get_dialogs(self, **kwargs: Any) -> Any: ...
    async def get_messages(self, entity: Any, **kwargs: Any) -> Any: ...
    async def send_read_acknowledge(self, entity: Any, *, max_id: int) -> Any: ...
    async def send_message(self, entity: Any, text: str, **kwargs: Any) -> Any: ...
    async def send_file(self, entity: Any, file: Any, **kwargs: Any) -> Any: ...
    async def send_code_request(self, phone: str) -> Any: ...
    async def sign_in(self, **kwargs: Any) -> Any: ...
    async def log_out(self) -> Any: ...
    async def qr_login(self) -> QRLoginGateway: ...
    async def download_profile_photo(
        self, entity: Any, **kwargs: Any
    ) -> bytes | None: ...
    async def __call__(self, request: Any) -> Any: ...
